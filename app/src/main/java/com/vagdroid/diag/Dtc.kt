    /** Расшифровка байта статуса KW1281. */
    fun statusDescription(status: Int): String {
        val s = status and 0x7F
        val base = when (s) {
            0x00 -> "не активен / нет доп. информации"
            0x01 -> "пассажирские коды"
            0x20 -> "недостаточно опоры для опознавания"
            0x21 -> "обрыв / замыкание на массу"
            0x22 -> "короткое замыкание на плюс"
            0x23 -> "неправдоподобный сигнал"
            0x24 -> "прерывание"
            0x25 -> "недопустимый уровень сигнала"
            0x26 -> "слишком малые значения сигнала"
            0x27 -> "слишком большие значения сигнала"
            0x28 -> "диапазон сигнала неверный"
            0x29 -> "внутренняя неисправность"
            0x2A -> "нет сигнала"
            0x2B -> "ошибка сигнала"
            in 0x2C..0x35 -> "неисправность на уровне установки"
            else -> "статус 0x%02X".format(s)
        }
        return if ((status and 0x80) != 0) "$base (спорадически)" else base
    }
